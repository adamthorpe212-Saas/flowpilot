/**
 * Concatenates every migration into supabase/all-migrations.sql.
 *
 * Applying migrations means pasting them into the Supabase SQL Editor by hand,
 * and eight separate pastes is eight chances to skip one or run them out of
 * order — which fails in confusing ways, because later migrations alter tables
 * earlier ones create.
 *
 * Regenerate after adding a migration:
 *   npm run build:migrations
 */
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import path from "node:path";

const dir = "supabase/migrations";
const output = "supabase/all-migrations.sql";

const files = readdirSync(dir)
  .filter((file) => file.endsWith(".sql"))
  .sort();

const lines = [
  "-- FlowPilot — all migrations, in order.",
  "--",
  "-- Generated by scripts/build-combined-migration.mjs. Do not edit directly;",
  "-- edit the files in supabase/migrations and regenerate.",
  "--",
  "-- Paste the whole file into the Supabase SQL Editor and run it once.",
  "-- Intended for a fresh project — it is not written to be re-run.",
  "",
];

for (const file of files) {
  lines.push(`-- ${"=".repeat(70)}`);
  lines.push(`-- ${file}`);
  lines.push(`-- ${"=".repeat(70)}`);
  lines.push("");
  lines.push(readFileSync(path.join(dir, file), "utf8").trim());
  lines.push("");
}

writeFileSync(output, `${lines.join("\n")}\n`);
console.log(`Combined ${files.length} migrations into ${output}`);
